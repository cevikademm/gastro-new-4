function merge(lang, data) {
  const file = path.join(I18N_DIR, `${lang}.json`);
  const raw = fs.readFileSync(file, 'utf8');
  const obj = JSON.parse(raw);

  // 1) planner namespace (new schema wins on conflicts)
  obj.planner = { ...(obj.planner || {}), ...data.planner };

  // 2) newsletter namespace
  obj.newsletter = { ...(obj.newsletter || {}), ...data.newsletter };

  // 3) welcome additions (merge inside obj.welcome)
  obj.welcome = { ...(obj.welcome || {}), ...data.welcomeAbout };

  // 4) blog additions (merge inside obj.blog — assume exists)
  obj.blog = { ...(obj.blog || {}), ...data.blogAdd };

  // 5) design additions (merge inside obj.design)
  obj.design = { ...(obj.design || {}), ...data.designAdd };

  // Preserve trailing newline if present in original
  const hasTrailingNewline = raw.endsWith('\n');
  const out = JSON.stringify(obj, null, 2) + (hasTrailingNewline ? '\n' : '');
  fs.writeFileSync(file, out, 'utf8');
  console.log(`✓ ${lang}.json updated`);
}

for (const [lang, data] of Object.entries(T)) {
  try {
    merge(lang, data);
  } catch (e) {
    console.error(`✗ ${lang}.json failed:`, e.message);
    process.exit(1);
  }
}

